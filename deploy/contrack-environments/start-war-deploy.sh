#!/usr/bin/env bash
# Enable the existing-Tomcat WAR-copy UI and verify the effective backend configuration.
# Run on the Linux Docker host. This script does not deploy a WAR or change Tomcat conf.
set -euo pipefail

fail() {
  printf 'ERROR: %s\n' "$*" >&2
  exit 1
}

SCRIPT_DIR="$(CDPATH= cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(CDPATH= cd -- "$SCRIPT_DIR/../.." && pwd)"
command -v docker >/dev/null 2>&1 || fail "Docker is not installed or is not on PATH."
command -v realpath >/dev/null 2>&1 || fail "realpath is required to resolve the existing environment directory."
docker compose version >/dev/null 2>&1 || fail "Docker Compose v2 is required."

CT_ENV_ROOT="${CT_ENV_ROOT:-$PROJECT_DIR/../Contrack-Recreate/contrack-env}"
CT_ENV_ROOT="$(realpath -e -- "$CT_ENV_ROOT")" || fail "CT_ENV_ROOT must point to the existing contrack-env directory."
test -d "$CT_ENV_ROOT" || fail "Environment root is not a directory: $CT_ENV_ROOT"
test -f "$CT_ENV_ROOT/runtime/server/conf/server.xml" || fail "Missing existing Tomcat conf/server.xml beneath $CT_ENV_ROOT/runtime/server"
test -d "$CT_ENV_ROOT/runtime/server/webapps" || fail "Missing existing Tomcat webapps directory."
test -f "$PROJECT_DIR/backend/app/modules/contrack_environments/war_deployment.py" || fail "Update the tool source to a version supporting Deploy WAR."

# Always use this script-owned configuration, not an old shell variable pointing to disabled YAML.
# The administrator's environment.yaml is left unchanged.
CONFIG_DIR="$(dirname -- "$CT_ENV_ROOT")/config"
mkdir -p -- "$CONFIG_DIR"
CT_ENV_CONFIG="$CONFIG_DIR/war-deploy.generated.yaml"
test ! -L "$CT_ENV_CONFIG" || fail "Generated configuration must not be a symbolic link."
if test -e "$CT_ENV_CONFIG"; then
  grep -qFx '# Generated by ConTrack start-war-deploy.sh; do not edit.' "$CT_ENV_CONFIG" || \
    fail "Refusing to overwrite a configuration not owned by this launcher: $CT_ENV_CONFIG"
fi
CONFIG_TEMP="$(mktemp "$CONFIG_DIR/.war-deploy.XXXXXX")"
trap 'rm -f -- "$CONFIG_TEMP"' EXIT
chmod 600 "$CONFIG_TEMP"
cat > "$CONFIG_TEMP" <<'YAML'
# Generated by ConTrack start-war-deploy.sh; do not edit.
enabled: true
operation_mode: deploy_war
server: runtime/server
YAML
mv -f -- "$CONFIG_TEMP" "$CT_ENV_CONFIG"
export CT_ENV_ROOT CT_ENV_CONFIG

cd -- "$PROJECT_DIR"
compose() {
  docker compose --project-directory "$PROJECT_DIR" \
    -f "$PROJECT_DIR/docker-compose.yml" \
    -f "$SCRIPT_DIR/compose.war-deploy.override.yaml" "$@"
}

printf 'Host and container root: %s\n' "$CT_ENV_ROOT"
printf 'Generated configuration: %s\n' "$CT_ENV_CONFIG"
compose config --quiet
compose up -d postgres redis
compose up -d --build --no-deps --force-recreate backend frontend

# Inspect inside the actual recreated backend, without printing secrets.
compose exec -T backend python - <<'PYTHON'
import os
from pathlib import Path
from app.modules.contrack_environments.config import load_settings

settings = load_settings()
expected = Path(os.environ["CONTRACK_ENV_ROOT"]).resolve()
print("config:", os.environ.get("CONTRACK_ENV_CONFIG"))
print("enabled:", settings.enabled)
print("mode:", getattr(settings, "operation_mode", "UNSUPPORTED"))
print("root:", settings.root)
print("WAR destination:", settings.path("server") / "webapps/contrack.war")
if not settings.enabled or getattr(settings, "operation_mode", None) != "deploy_war":
    raise SystemExit("ERROR: Backend has not loaded deploy_war configuration.")
if settings.root.resolve() != expected:
    raise SystemExit("ERROR: Effective root differs from the bind mount root.")
if not (settings.path("server") / "conf/server.xml").is_file():
    raise SystemExit("ERROR: Existing Tomcat conf is not visible inside the backend.")
if not (settings.path("server") / "webapps").is_dir():
    raise SystemExit("ERROR: Existing Tomcat webapps is not visible inside the backend.")
print("VERIFIED: enabled=True, mode=deploy_war, root and Tomcat mount are correct.")
PYTHON

printf '\nReload the frontend with Ctrl+F5. Expected form: ConTrack WAR / Deploy WAR.\n'
printf 'No WAR has been copied by this launcher; deploy from the user interface.\n'
